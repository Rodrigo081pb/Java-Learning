public class Main {

    /*
     * public   : modificador de acesso (acessível de qualquer lugar)
     * static   : pertence à classe, não ao objeto
     * void     : não retorna nenhum valor
     * main     : método principal, ponto de entrada do programa
     * String[] : array de Strings que recebe os argumentos da linha de comando
     * args     : nome da variável que armazena esses argumentos
     */

    public static void main(String[] args) {
        int numero = 1;
        Integer numero2 = null;
        System.out.println(numero2);

    }
}